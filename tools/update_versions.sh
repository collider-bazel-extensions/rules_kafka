#!/usr/bin/env bash
# Regenerates private/versions.bzl: the Apache Kafka binary release
# kafka_server runs, pinned by its published sha512.
#
#   tools/update_versions.sh [<kafka version>] [--check]
#
# - <version> defaults to the latest release listed at
#   https://downloads.apache.org/kafka/ (only 4.x and later: kafka_server is
#   KRaft-only). Older releases leave downloads.apache.org; they are fetched
#   from https://archive.apache.org/dist/kafka/ instead.
# - The archive is kafka_2.13-<version>.tgz. Its sha512 is the published
#   kafka_2.13-<version>.tgz.sha512 (gpg --print-md format, normalised to
#   lowercase hex); the downloaded archive must hash to it.
# - --check: regenerate into a temp file and diff against the checked-in
#   one (exit 1 on a difference), downloading and verifying again.
#
# Needs curl, python3 and sha512sum (or shasum -a 512).
set -euo pipefail

SCALA=2.13
DOWNLOADS=https://downloads.apache.org/kafka
ARCHIVE=https://archive.apache.org/dist/kafka

repo="$(cd "$(dirname "$0")/.." && pwd)"
out="$repo/private/versions.bzl"
version=""
check=0
while [[ $# -gt 0 ]]; do
    case "$1" in
        --check) check=1 ;;
        -*) echo "unknown flag: $1" >&2; exit 2 ;;
        *) version="$1" ;;
    esac
    shift
done

work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT

if [[ -z "$version" ]]; then
    version="$(curl -sSfL "$DOWNLOADS/" | python3 -c '
import re, sys
vs = set(re.findall(r"href=\"(\d+\.\d+\.\d+)/\"", sys.stdin.read()))
vs = [v for v in vs if int(v.split(".")[0]) >= 4]
print(max(vs, key=lambda v: tuple(map(int, v.split(".")))) if vs else "")
')"
    [[ -n "$version" ]] || { echo "no Kafka 4.x release listed at $DOWNLOADS/" >&2; exit 1; }
fi
if [[ "${version%%.*}" -lt 4 ]]; then
    echo "Kafka $version: kafka_server needs Kafka 4.x or later (KRaft only)" >&2
    exit 1
fi
tgz="kafka_${SCALA}-${version}.tgz"

base=""
for b in "$DOWNLOADS" "$ARCHIVE"; do
    if curl -sSfL -o "$work/$tgz.sha512" "$b/$version/$tgz.sha512" 2>/dev/null; then base="$b"; break; fi
done
[[ -n "$base" ]] || { echo "no $tgz.sha512 at $DOWNLOADS or $ARCHIVE" >&2; exit 1; }
# "kafka_2.13-4.4.0.tgz: F5CEBA8A 265AB6BB ..." (or "<hex>  <file>") -> lowercase hex.
sha="$(python3 - "$work/$tgz.sha512" "$tgz" <<'EOF'
import re, sys
text = open(sys.argv[1]).read()
name = sys.argv[2]
if text.lstrip().startswith(name):
    text = text.split(":", 1)[1]
hexd = "".join(re.findall(r"[0-9A-Fa-f]+", text.replace(name, ""))).lower()
if len(hexd) != 128:
    sys.exit(f"can't read a sha512 from {sys.argv[1]}: {text!r}")
print(hexd)
EOF
)"
echo "Kafka $version: $tgz sha512 $sha (from $base)" >&2
curl -sSfL -o "$work/$tgz" "$base/$version/$tgz"
if command -v sha512sum >/dev/null; then
    echo "$sha  $work/$tgz" | sha512sum -c --quiet - >&2
else
    echo "$sha  $work/$tgz" | shasum -a 512 -c --quiet - >&2
fi
prefix="$(tar -tzf "$work/$tgz" | head -n 1 | cut -d/ -f1)"
[[ "$prefix" == "kafka_${SCALA}-${version}" ]] || { echo "unexpected top directory $prefix in $tgz" >&2; exit 1; }
tar -tzf "$work/$tgz" "$prefix/libs/kafka-clients-${version}.jar" >/dev/null \
    || { echo "$tgz has no libs/kafka-clients-${version}.jar" >&2; exit 1; }

cat > "$work/versions.bzl" <<EOF
"""Generated by tools/update_versions.sh — do not edit by hand.

Schema:

    KAFKA_VERSIONS = {
        "<version>": {
            "urls": [<downloads.apache.org url>, <archive.apache.org url>],
            "sha512": "<the published .sha512, lowercase hex>",
            "strip_prefix": "kafka_<scala>-<version>",
        },
    }
"""

DEFAULT_VERSION = "$version"

KAFKA_VERSIONS = {
    "$version": {
        "urls": [
            "$DOWNLOADS/$version/$tgz",
            "$ARCHIVE/$version/$tgz",
        ],
        "sha512": "$sha",
        "strip_prefix": "$prefix",
    },
}
EOF

if [[ "$check" == 1 ]]; then
    if diff -u "$out" "$work/versions.bzl"; then
        echo "versions.bzl is up to date" >&2
    else
        echo "versions.bzl differs from a fresh generation (above)" >&2
        exit 1
    fi
else
    cp "$work/versions.bzl" "$out"
    echo "wrote $out" >&2
fi
